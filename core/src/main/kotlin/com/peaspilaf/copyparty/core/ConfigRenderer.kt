package com.peaspilaf.copyparty.core

/**
 * Renders [AppState] into a copyparty config file (`-c <file>`).
 *
 * The output is deterministic: same state in, byte-identical config out. That is what makes the
 * golden tests in `ConfigRendererTest` and the real-server contract check in CI possible.
 */
object ConfigRenderer {
    const val GENERATED_HEADER = "# generated by copyparty-android -- edits are overwritten on every save"

    /** @param logPath when non-null, copyparty logs to this file instead of stdout. */
    fun render(state: AppState, logPath: String? = null): String {
        val out = StringBuilder()
        out.append(GENERATED_HEADER).append('\n')
        out.append('\n')

        out.append("[global]\n")
        out.append("  p: ").append(state.settings.port).append('\n')
        out.append("  i: ").append(if (state.settings.lanAccess) "0.0.0.0" else "127.0.0.1").append('\n')
        // The app is a LAN file server, not a web site: plain http keeps every client happy.
        out.append("  http-only\n")
        out.append("  no-crt\n")
        out.append("  no-robots\n")
        out.append("  q\n")
        out.append("  no-voldump\n")
        val name = sanitizeInline(state.settings.serverName)
        if (name.isNotEmpty()) {
            out.append("  name: ").append(name).append('\n')
        }
        if (logPath != null) {
            out.append("  lo: ").append(sanitizeInline(logPath)).append('\n')
            out.append("  flo: 2\n")
        }
        out.append('\n')

        val users = state.users
            .filter { it.name.isNotBlank() && it.password.isNotEmpty() }
            .sortedBy { it.name }
        if (users.isNotEmpty()) {
            out.append("[accounts]\n")
            for (user in users) {
                out.append("  ").append(user.name).append(": ").append(sanitizeInline(user.password)).append('\n')
            }
            out.append('\n')
        }

        val shares = state.shares.filter { it.enabled }
        for (share in shares) {
            out.append('[').append(mountPath(share.urlPath)).append("]\n")
            out.append("  ").append(sanitizeInline(share.localPath)).append('\n')
            val grantLines = share.grants
                .filter { it.permissions.isNotEmpty() }
                .map { accsFlags(it.permissions) to it.principal }
                .sortedWith(compareBy({ it.first }, { it.second }))
            if (grantLines.isNotEmpty()) {
                out.append("  accs:\n")
                for ((flags, principal) in grantLines) {
                    out.append("    ").append(flags).append(": ").append(principal).append('\n')
                }
            }
            if (share.grants.any { Permission.UPLOAD in it.permissions }) {
                // e2d enables the upload database: resumable uploads, dedupe and upload-undo.
                out.append("  flags:\n")
                out.append("    e2d\n")
            }
            out.append('\n')
        }

        // End the file with exactly one newline. Only newlines are trimmed, so a trailing space that
        // belongs to the last value is not silently removed: the renderer reproduces the state it is
        // given instead of "fixing" it. (copyparty trims config values when it parses them, so a
        // folder whose name really ends in a space has to be rejected earlier by the Validator --
        // the renderer must not hide that by rewriting the value.)
        return out.toString().trimEnd('\n') + "\n"
    }

    /** `photos` -> `/photos`; copyparty mounts volumes by web path. */
    fun mountPath(urlPath: String): String = "/" + urlPath.trim().removePrefix("/").trimEnd('/')

    /** copyparty accs flags, e.g. `rw`. A readable user does not also need `g`. */
    fun accsFlags(permissions: Set<Permission>): String {
        val flags = StringBuilder()
        if (Permission.VIEW in permissions) flags.append(Permission.VIEW.flag)
        if (Permission.DOWNLOAD in permissions && Permission.VIEW !in permissions) flags.append(Permission.DOWNLOAD.flag)
        if (Permission.UPLOAD in permissions) flags.append(Permission.UPLOAD.flag)
        if (Permission.MOVE in permissions) flags.append(Permission.MOVE.flag)
        if (Permission.DELETE in permissions) flags.append(Permission.DELETE.flag)
        if (Permission.ADMIN in permissions) flags.append(Permission.ADMIN.flag)
        return flags.toString()
    }

    /** Config files are line based, so values may never contain a line break. */
    private fun sanitizeInline(value: String): String = value.replace('\n', ' ').replace('\r', ' ')
}
