package com.peaspilaf.copyparty.core

import com.google.common.truth.Truth.assertThat
import org.junit.Test

/**
 * The generated copyparty.conf is the file the phone actually runs, so these tests treat it as a
 * file format rather than as text: exact bytes, one value per line, stable ordering.
 *
 * CI pipes this same renderer's output into real copyparty, which is why an extra blank line or a
 * reordered ACL flag is a behaviour change and not a style choice.
 */
class ConfigRendererTest {
    private val logPath = "/data/user/0/com.peaspilaf.copyparty.debug/files/copyparty/copyparty.log"

    private fun state(
        users: List<User> = listOf(User("alice", "hunter2")),
        shares: List<Share> = listOf(
            Share(
                id = "s1",
                name = "Photos",
                urlPath = "photos",
                localPath = "/storage/emulated/0/DCIM",
                grants = listOf(
                    Grant(Grant.EVERYONE, setOf(Permission.VIEW)),
                    Grant("alice", setOf(Permission.VIEW, Permission.UPLOAD)),
                ),
            ),
        ),
        settings: ServerSettings = ServerSettings(),
    ) = AppState(users = users, shares = shares, settings = settings)

    /** Three shares and two accounts: the smallest state that exercises every part of the file. */
    private fun canonicalState() = AppState(
        users = listOf(User("alice", "hunter2"), User("bob", "letmein")),
        shares = listOf(
            Share(
                id = "s-photos",
                name = "Photos",
                urlPath = "photos",
                localPath = "/storage/emulated/0/DCIM/Camera",
                grants = listOf(
                    Grant(Grant.EVERYONE, setOf(Permission.VIEW)),
                    Grant("alice", setOf(Permission.VIEW, Permission.UPLOAD)),
                ),
            ),
            Share(
                id = "s-private",
                name = "Private",
                urlPath = "private",
                localPath = "/storage/emulated/0/Documents/private",
                grants = listOf(
                    Grant(
                        "bob",
                        setOf(
                            Permission.VIEW,
                            Permission.DOWNLOAD,
                            Permission.UPLOAD,
                            Permission.MOVE,
                            Permission.DELETE,
                            Permission.ADMIN,
                        ),
                    ),
                ),
            ),
            Share(
                id = "s-public",
                name = "Public",
                urlPath = "public",
                localPath = "/storage/emulated/0/Pictures",
                grants = listOf(Grant(Grant.EVERYONE, setOf(Permission.VIEW))),
            ),
        ),
        settings = ServerSettings(),
    )

    @Test
    fun `the canonical state renders this exact config`() {
        val conf = ConfigRenderer.render(canonicalState())
        assertThat(conf).startsWith(ConfigRenderer.GENERATED_HEADER + "\n")

        // The renderer always ends the file with exactly one newline.
        val expected = """
            # generated by copyparty-android -- edits are overwritten on every save

            [global]
              p: 3923
              i: 0.0.0.0
              http-only
              no-crt
              no-robots
              q
              no-voldump
              name: copyparty

            [accounts]
              alice: hunter2
              bob: letmein

            [/photos]
              /storage/emulated/0/DCIM/Camera
              accs:
                r: *
                rw: alice
              flags:
                e2d

            [/private]
              /storage/emulated/0/Documents/private
              accs:
                rwmda: bob
              flags:
                e2d

            [/public]
              /storage/emulated/0/Pictures
              accs:
                r: *
        """.trimIndent() + "\n"

        assertThat(conf).isEqualTo(expected)
    }

    @Test
    fun `the canonical state renders this exact config with a log file`() {
        val conf = ConfigRenderer.render(canonicalState(), logPath)

        // The same file as above plus the two logging lines the app adds when it runs the server.
        val expected = """
            # generated by copyparty-android -- edits are overwritten on every save

            [global]
              p: 3923
              i: 0.0.0.0
              http-only
              no-crt
              no-robots
              q
              no-voldump
              name: copyparty
              lo: /data/user/0/com.peaspilaf.copyparty.debug/files/copyparty/copyparty.log
              flo: 2

            [accounts]
              alice: hunter2
              bob: letmein

            [/photos]
              /storage/emulated/0/DCIM/Camera
              accs:
                r: *
                rw: alice
              flags:
                e2d

            [/private]
              /storage/emulated/0/Documents/private
              accs:
                rwmda: bob
              flags:
                e2d

            [/public]
              /storage/emulated/0/Pictures
              accs:
                r: *
        """.trimIndent() + "\n"

        assertThat(conf).isEqualTo(expected)
    }

    @Test
    fun `renders global section with plain http and the configured port`() {
        val conf = ConfigRenderer.render(state(settings = ServerSettings(port = 4242, lanAccess = false)))
        assertThat(conf).contains("[global]\n  p: 4242\n  i: 127.0.0.1\n")
        assertThat(conf).contains("  http-only\n")
        assertThat(conf).contains("  no-crt\n")
    }

    @Test
    fun `renders accounts and volume acl lines`() {
        val conf = ConfigRenderer.render(state())
        assertThat(conf).contains("[accounts]\n  alice: hunter2\n")
        assertThat(conf).contains("[/photos]\n  /storage/emulated/0/DCIM\n  accs:\n")
        assertThat(conf).contains("    r: *\n")
        assertThat(conf).contains("    rw: alice\n")
        assertThat(conf).contains("  flags:\n    e2d\n")
    }

    @Test
    fun `a readable user does not also get the get-only flag`() {
        assertThat(ConfigRenderer.accsFlags(setOf(Permission.VIEW, Permission.DOWNLOAD))).isEqualTo("r")
        assertThat(ConfigRenderer.accsFlags(setOf(Permission.DOWNLOAD))).isEqualTo("g")
        assertThat(ConfigRenderer.accsFlags(setOf(Permission.UPLOAD, Permission.DELETE))).isEqualTo("wd")
    }

    @Test
    fun `flags are written in copyparty order whatever order the permission set iterates`() {
        // Sets keep their insertion order, so the set order must not leak into the config.
        assertThat(ConfigRenderer.accsFlags(setOf(Permission.MOVE, Permission.DELETE, Permission.UPLOAD)))
            .isEqualTo("wmd")
        assertThat(ConfigRenderer.accsFlags(setOf(Permission.DELETE, Permission.VIEW, Permission.UPLOAD)))
            .isEqualTo("rwd")
        assertThat(
            ConfigRenderer.accsFlags(
                setOf(
                    Permission.ADMIN,
                    Permission.DELETE,
                    Permission.MOVE,
                    Permission.UPLOAD,
                    Permission.DOWNLOAD,
                    Permission.VIEW,
                ),
            ),
        ).isEqualTo("rwmda")
        assertThat(ConfigRenderer.accsFlags(setOf(Permission.ADMIN))).isEqualTo("a")
        assertThat(ConfigRenderer.accsFlags(emptySet())).isEmpty()
    }

    @Test
    fun `disabled shares are not rendered`() {
        val conf = ConfigRenderer.render(state(shares = listOf(Share("s1", "x", "x", "/tmp/x", enabled = false))))
        assertThat(conf).doesNotContain("[/x]")
        assertThat(conf).doesNotContain("/tmp/x")
    }

    @Test
    fun `accounts are sorted by user name`() {
        val conf = ConfigRenderer.render(
            state(users = listOf(User("zoe", "pw-zoe"), User("alice", "pw-alice"), User("bob", "pw-bob"))),
        )
        assertThat(conf).contains("[accounts]\n  alice: pw-alice\n  bob: pw-bob\n  zoe: pw-zoe\n")
    }

    @Test
    fun `a user without a name or without a password never gets an account line`() {
        // Skipping them is what keeps the config parseable; saving such a user is refused elsewhere.
        val conf = ConfigRenderer.render(
            state(users = listOf(User("alice", "hunter2"), User("", "secret"), User("nopass", ""))),
        )
        assertThat(conf).contains("[accounts]\n  alice: hunter2\n")
        assertThat(conf).doesNotContain("secret")
        assertThat(conf).doesNotContain("nopass")
    }

    @Test
    fun `grant lines are sorted by flags and then by principal`() {
        val conf = ConfigRenderer.render(
            state(
                users = listOf(User("alice", "hunter2"), User("bob", "letmein")),
                shares = listOf(
                    Share(
                        id = "s1",
                        name = "Mixed",
                        urlPath = "mixed",
                        localPath = "/storage/emulated/0/Mixed",
                        grants = listOf(
                            Grant("alice", setOf(Permission.VIEW)),
                            Grant("bob", setOf(Permission.DOWNLOAD)),
                            Grant(Grant.EVERYONE, setOf(Permission.VIEW)),
                        ),
                    ),
                ),
            ),
        )
        // "g" sorts before "r", and two "r" grants are broken up by principal ("*" before names).
        assertThat(conf).contains("  accs:\n    g: bob\n    r: *\n    r: alice\n")
    }

    @Test
    fun `the same grants in a different order render the same config`() {
        val grants = listOf(
            Grant("alice", setOf(Permission.VIEW, Permission.UPLOAD)),
            Grant("bob", setOf(Permission.MOVE, Permission.DELETE)),
            Grant(Grant.EVERYONE, setOf(Permission.VIEW)),
        )
        val share = Share("s1", "Mixed", "mixed", "/storage/emulated/0/Mixed", grants)
        val users = listOf(User("alice", "hunter2"), User("bob", "letmein"))

        val asEntered = ConfigRenderer.render(state(users = users, shares = listOf(share)))
        val reversed = ConfigRenderer.render(state(users = users, shares = listOf(share.copy(grants = grants.reversed()))))

        assertThat(reversed).isEqualTo(asEntered)
    }

    @Test
    fun `only shares where someone may upload get the e2d upload flags`() {
        val conf = ConfigRenderer.render(
            state(
                shares = listOf(
                    Share(
                        id = "s-up",
                        name = "Drop box",
                        urlPath = "drop",
                        localPath = "/storage/emulated/0/Download/drop",
                        grants = listOf(Grant("alice", setOf(Permission.UPLOAD))),
                    ),
                    Share(
                        id = "s-read",
                        name = "Read only",
                        urlPath = "read",
                        localPath = "/storage/emulated/0/Pictures",
                        grants = listOf(Grant(Grant.EVERYONE, setOf(Permission.VIEW))),
                    ),
                    Share(
                        id = "s-none",
                        name = "Nobody",
                        urlPath = "none",
                        localPath = "/storage/emulated/0/Movies",
                    ),
                ),
            ),
        )

        assertThat(conf.lines().count { it == "  flags:" }).isEqualTo(1)
        assertThat(conf).contains("[/drop]\n  /storage/emulated/0/Download/drop\n  accs:\n    w: alice\n  flags:\n    e2d\n")
        assertThat(conf.substringAfter("[/read]")).doesNotContain("flags:")
        assertThat(conf.substringAfter("[/none]")).doesNotContain("flags:")
    }

    @Test
    fun `lan access binds every interface and local-only mode binds loopback`() {
        val lan = ConfigRenderer.render(state(settings = ServerSettings(lanAccess = true)))
        assertThat(lan).contains("  i: 0.0.0.0\n")
        assertThat(lan).doesNotContain("127.0.0.1")

        val localOnly = ConfigRenderer.render(state(settings = ServerSettings(lanAccess = false)))
        assertThat(localOnly).contains("  i: 127.0.0.1\n")
        assertThat(localOnly).doesNotContain("0.0.0.0")
    }

    @Test
    fun `the server name and the log path are inlined on one line`() {
        // Config files are line based: a line break inside a value would silently add a setting.
        val conf = ConfigRenderer.render(
            state(settings = ServerSettings(serverName = "my\r\nphone")),
            logPath = "/data/copy\nparty.log",
        )
        assertThat(conf).contains("  name: my  phone\n")
        assertThat(conf).contains("  lo: /data/copy party.log\n")
        assertThat(conf).doesNotContain("my\nphone")
        assertThat(conf).doesNotContain("copy\nparty")
    }

    @Test
    fun `mount paths always start with exactly one slash`() {
        assertThat(ConfigRenderer.mountPath("photos")).isEqualTo("/photos")
        assertThat(ConfigRenderer.mountPath("/photos")).isEqualTo("/photos")
        assertThat(ConfigRenderer.mountPath("photos/")).isEqualTo("/photos")
        assertThat(ConfigRenderer.mountPath("/photos/")).isEqualTo("/photos")
    }

    @Test
    fun `an empty state is a valid config with only a global section`() {
        val expected = """
            # generated by copyparty-android -- edits are overwritten on every save

            [global]
              p: 3923
              i: 0.0.0.0
              http-only
              no-crt
              no-robots
              q
              no-voldump
              name: copyparty
        """.trimIndent() + "\n"

        val conf = ConfigRenderer.render(AppState())

        assertThat(conf).isEqualTo(expected)
        assertThat(conf).doesNotContain("[accounts]")
        assertThat(conf).doesNotContain("\n[/")
    }

    @Test
    fun `rendering is deterministic`() {
        val rendered = ConfigRenderer.render(state())
        assertThat(ConfigRenderer.render(state())).isEqualTo(rendered)
    }

    /**
     * Expert mode is not a second config: it is the same file with the power user's raw global
     * directives appended to `[global]` and extra volume flags merged into the volume's single flags
     * value. The ordering is fixed so the file stays diffable and the contract job reproducible.
     */
    @Test
    fun `expert global args and volume flags render deterministically`() {
        val expert = AppState(
            users = listOf(User("alice", "hunter2")),
            shares = listOf(
                Share(
                    id = "s-photos",
                    name = "Photos",
                    urlPath = "photos",
                    localPath = "/storage/emulated/0/DCIM/Camera",
                    grants = listOf(
                        Grant(Grant.EVERYONE, setOf(Permission.VIEW)),
                        Grant("alice", setOf(Permission.VIEW, Permission.UPLOAD)),
                    ),
                    extraVolFlags = " nodupe , nosub ",
                ),
            ),
            settings = ServerSettings(expertMode = true, extraArgs = "  --dedup\n\n  --no-dupe  "),
        )

        val expected = """
            # generated by copyparty-android -- edits are overwritten on every save

            [global]
              p: 3923
              i: 0.0.0.0
              http-only
              no-crt
              no-robots
              q
              no-voldump
              name: copyparty
              lo: /tmp/copyparty.log
              flo: 2
              --dedup
              --no-dupe

            [accounts]
              alice: hunter2

            [/photos]
              /storage/emulated/0/DCIM/Camera
              accs:
                r: *
                rw: alice
              flags:
                e2d, nodupe, nosub
        """.trimIndent() + "\n"

        val rendered = ConfigRenderer.render(expert, "/tmp/copyparty.log")
        assertThat(rendered).isEqualTo(expected)
        // Same state in, byte-identical file out - that is what the golden test protects.
        assertThat(ConfigRenderer.render(expert, "/tmp/copyparty.log")).isEqualTo(rendered)

        // Expert mode is a switch on the screens, not a switch on the server: hiding the expert fields
        // must not silently drop the directives the user already saved.
        val hiddenExpertMode = expert.copy(settings = expert.settings.copy(expertMode = false))
        assertThat(ConfigRenderer.render(hiddenExpertMode, "/tmp/copyparty.log")).isEqualTo(rendered)

        // A blank expert value adds nothing, and the config still ends with exactly one newline.
        val noExtras = expert.copy(
            shares = listOf(expert.shares[0].copy(extraVolFlags = "")),
            settings = expert.settings.copy(extraArgs = "   \n\n  "),
        )
        val plain = ConfigRenderer.render(noExtras, "/tmp/copyparty.log")
        assertThat(plain).doesNotContain("--dedup")
        assertThat(plain).endsWith("    e2d\n")
        assertThat(plain.endsWith("\n\n")).isFalse()
    }

    @Test
    fun `advanced folder flags are written even when nobody may upload`() {
        // Extra volflags are a volume setting of their own; they must not be tied to the e2d upload rule.
        val conf = ConfigRenderer.render(
            AppState(
                shares = listOf(
                    Share(
                        id = "s-docs",
                        name = "Docs",
                        urlPath = "docs",
                        localPath = "/storage/emulated/0/Documents",
                        grants = listOf(Grant(Grant.EVERYONE, setOf(Permission.VIEW))),
                        extraVolFlags = "nodupe",
                    ),
                ),
            ),
        )

        assertThat(conf).contains("[/docs]\n  /storage/emulated/0/Documents\n  accs:\n    r: *\n  flags:\n    nodupe\n")
    }

    @Test
    fun `a section header can never be injected through expert values`() {
        // The renderer drops a `[section]` line outright; the Validator refuses such a state before it
        // gets here, so this is the second lock on the same door.
        val conf = ConfigRenderer.render(
            AppState(
                shares = listOf(
                    Share(
                        id = "s1",
                        name = "Photos",
                        urlPath = "photos",
                        localPath = "/storage/photos",
                        extraVolFlags = "[evil], nodupe",
                    ),
                ),
                settings = ServerSettings(extraArgs = "--dedup\n  [evil]\n--no-dupe"),
            ),
        )

        assertThat(conf).doesNotContain("[evil]")
        assertThat(conf).doesNotContain("\n[/evil]")
        assertThat(conf).contains("  --dedup\n  --no-dupe\n")
        assertThat(conf).contains("  flags:\n    nodupe\n")
        // The share the user actually configured is still there.
        assertThat(conf).contains("[/photos]\n")
    }
}
